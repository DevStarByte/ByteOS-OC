-- Symbolic links (ln -s, readlink, realpath and how the other tools treat
-- them) and the umask for new files.
users()
put("/tmp/data/a.txt", "alpha\n")
put("/tmp/data/sub/b.txt", "beta\n")

test("a link to a file and to a directory", function()
  eq(select(2, run("ln -s /tmp/data/a.txt /tmp/la")), 0)
  eq(run("cat /tmp/la"), "alpha\n")
  run("ln -s /tmp/data /tmp/ld")
  eq(run("cat /tmp/ld/sub/b.txt"), "beta\n")
  eq(run("readlink /tmp/la"), "/tmp/data/a.txt\n")
  eq(run("realpath /tmp/ld/sub"), "/tmp/data/sub\n")
  eq(run("cd /tmp/ld; pwd; ls"), "/tmp/ld\nsub\na.txt\n", "cd and ls through it")
  eq(run("cd /"), "")
  run("echo more >> /tmp/la")
  eq(file("/tmp/data/a.txt"), "alpha\nmore\n", "writing goes to the target")
  has(file("/var/lib/links"), "/tmp/la\t/tmp/data/a.txt\n", "kept in /var/lib/links")
end)

test("relative and dangling links; ln -s into a directory, -f, no hard links", function()
  run("ln -s sub/b.txt /tmp/data/rel")
  eq(run("cat /tmp/data/rel"), "beta\n", "relative to the link's directory")
  eq(run("readlink -f /tmp/data/rel"), "/tmp/data/sub/b.txt\n")
  run("ln -s /tmp/nowhere /tmp/dangle")
  eq(kernel.fs.exists("/tmp/dangle"), false)
  eq(run("readlink /tmp/dangle"), "/tmp/nowhere\n")
  has(run("ls /tmp"), "dangle", "listed although it leads nowhere")
  local out, rc = run("realpath /tmp/dangle")
  eq(rc, 1); has(out, "no such file")
  run("ln -s /etc/motd /tmp/data/")
  eq(run("readlink /tmp/data/motd"), "/etc/motd\n")
  has(run("ln -s /etc/hostname /tmp/la"), "file exists")
  eq(select(2, run("ln -sf /etc/hostname /tmp/la")), 0)
  eq(run("readlink /tmp/la"), "/etc/hostname\n")
  eq(file("/tmp/data/a.txt"), "alpha\nmore\n", "-f replaced the link, not the file")
  local hard, hrc = run("ln /tmp/data/a.txt /tmp/hard")
  eq(hrc, 1); has(hard, "use ln -s")
end)

test("ls -l, find and du", function()
  local out = run("ls -l /tmp")
  has(out, "lrwxrwxrwx"); has(out, "la -> /etc/hostname"); has(out, "ld -> /tmp/data")
  eq(run("find /tmp -type l | sort"), "/tmp/dangle\n/tmp/data/motd\n/tmp/data/rel\n/tmp/la\n/tmp/ld\n")
  lacks(run("find /tmp"), "/tmp/ld/sub", "find does not walk through links")
  eq(run("du -s /tmp/ld"), (run("du -s /tmp/data"):gsub("/tmp/data", "/tmp/ld")), "a link named on the command line is followed")
end)

test("rm and mv act on the link itself", function()
  run("rm /tmp/dangle")
  eq(kernel.fs.readlink("/tmp/dangle"), nil)
  run("rm -r /tmp/ld")
  eq(kernel.fs.readlink("/tmp/ld"), nil, "the link is gone")
  eq(file("/tmp/data/sub/b.txt"), "beta\n", "the directory it led to is not")
  run("mv /tmp/la /tmp/lb")
  eq(run("readlink /tmp/lb"), "/etc/hostname\n")
  eq(kernel.fs.readlink("/tmp/la"), nil)
  run("mv /tmp/data /tmp/moved")
  eq(run("readlink /tmp/moved/rel"), "sub/b.txt\n", "links move with their directory")
  eq(run("cat /tmp/moved/rel"), "beta\n")
  run("rm -r /tmp/moved/sub")
  run("rm -r /tmp/moved")
  lacks(file("/var/lib/links"), "/tmp/moved", "a removed directory takes its links along")
end)

test("cp follows a link, cp -r copies links as links", function()
  put("/tmp/src/f.txt", "f\n")
  run("ln -s f.txt /tmp/src/lf")
  run("cp /tmp/src/lf /tmp/copy.txt")
  eq(file("/tmp/copy.txt"), "f\n")
  eq(kernel.fs.readlink("/tmp/copy.txt"), nil)
  run("cp -r /tmp/src /tmp/dst")
  eq(run("readlink /tmp/dst/lf"), "f.txt\n")
  eq(run("cat /tmp/dst/lf"), "f\n")
end)

test("a circle of links is an error, not a hang", function()
  run("ln -s /tmp/c2 /tmp/c1; ln -s /tmp/c1 /tmp/c2")
  has(run("cat /tmp/c1"), "/tmp/c1: no such file")
  has(run("readlink -f /tmp/c1"), "too many levels")
  eq(kernel.fs.exists("/tmp/c1"), false)
  run("rm /tmp/c1 /tmp/c2")
end)

test("links do not get around permissions", function()
  run("ln -s /etc/shadow /tmp/sh")
  as("bob", function()
    has(run("cat /tmp/sh"), "permission denied")
    has(run("ln -s /tmp /etc/evil"), "permission denied")
    has(run("echo x > /tmp/sh"), "permission denied")
    run("ln -s /tmp /home/bob/t")
    eq(run("readlink /home/bob/t"), "/tmp\n", "in their own home they may")
    has(run("rm /tmp/sh"), "", "/tmp is open to everyone")
  end)
  as("alice", function() has(run("rm /home/bob/t"), "permission denied") end)
  ok(file("/etc/shadow"):find("root:"), "shadow untouched")
end)

test("umask gives new files and directories their mode", function()
  run("touch /tmp/plain")
  eq(kernel.fs.stat("/tmp/plain").listed, false, "the default 022 lists nothing")
  as("alice", function()
    local old = kernel.fs.umask(63) -- 077
    eq(old, 18)
    run("touch /home/alice/secret; mkdir /home/alice/private")
    has(run("ls -l /home/alice"), "-rw-------  alice users")
    has(run("ls -l /home/alice"), "drwx------  alice users")
    kernel.fs.umask(18)
    run("touch /home/alice/normal")
    eq(kernel.fs.stat("/home/alice/normal").listed, false)
  end)
  as("bob", function()
    eq(kernel.fs.umask(), 18, "each user has their own")
    has(run("cat /home/alice/secret"), "permission denied")
  end)
end)
