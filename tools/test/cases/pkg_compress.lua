-- The packages gzip (gzip, gunzip, zcat and tar -z) and xxd, checked
-- against the PC's own gzip and tar.
users()
local P = dofile(REPO .. "/tools/test/pkgrepo.lua")
if not P then return end
local function q(p) return "'" .. p:gsub("'", "'\\''") .. "'" end
local function host(cmd) local h = io.popen(cmd .. " 2>&1"); local out = h:read("a"); h:close(); return out end

-- some bytes that do not shrink, and text that does
local function noise(n, seed)
  local t, x = {}, seed or 12345
  for i = 1, n do x = (x * 1103515245 + 12345) % 2147483648; t[i] = string.char((x >> 16) % 256) end
  return table.concat(t)
end
local TEXT = string.rep("ByteOS packs this line, and the next one looks just like it.\n", 1700) -- ~100 KiB
local BIN = noise(40000)
put("/tmp/src/a.txt", "hello\n")
put("/tmp/src/sub/b.bin", BIN)

test("tar -z without the gzip package says what to install", function()
  lacks(run(P .. "-S tar xxd"), "error")
  local out, rc = run("tar -czf /tmp/x.tgz -C /tmp src")
  eq(rc, 2); has(out, "tar -z needs the gzip package: pacman -S gzip")
end)

test("gzip and gunzip replace the file; the PC's gzip agrees", function()
  lacks(run(P .. "-S gzip"), "error")
  put("/tmp/g/notes.txt", TEXT)
  local _, rc = run("gzip /tmp/g/notes.txt")
  eq(rc, 0)
  ok(not file("/tmp/g/notes.txt"), "the original is gone")
  local gz = file("/tmp/g/notes.txt.gz")
  ok(gz and #gz < #TEXT // 10, "text shrinks a lot: " .. tostring(gz and #gz))
  eq(host("gzip -dc " .. q(ROOT .. "/tmp/g/notes.txt.gz")), TEXT, "the PC unpacks it")
  eq(select(2, run("gunzip /tmp/g/notes.txt.gz")), 0)
  eq(file("/tmp/g/notes.txt"), TEXT); ok(not file("/tmp/g/notes.txt.gz"), ".gz is gone")
end)

test("binary data both ways, -k, -c, levels, zcat and pipes", function()
  put("/tmp/g/data.bin", BIN)
  run("gzip -k -9 /tmp/g/data.bin")
  ok(file("/tmp/g/data.bin"), "-k keeps the original")
  eq(host("gzip -dc " .. q(ROOT .. "/tmp/g/data.bin.gz")), BIN, "binary, unpacked by the PC")
  ok(#file("/tmp/g/data.bin.gz") < #BIN + 64, "data that does not shrink barely grows")
  os.execute("gzip -c " .. q(ROOT .. "/tmp/g/data.bin") .. " > " .. q(ROOT .. "/tmp/g/pc.bin.gz"))
  os.execute("gzip -c " .. q(ROOT .. "/tmp/g/notes.txt") .. " > " .. q(ROOT .. "/tmp/g/pc.txt.gz"))
  run("gunzip /tmp/g/pc.bin.gz /tmp/g/pc.txt.gz")
  eq(file("/tmp/g/pc.bin"), BIN, "the PC's binary .gz"); eq(file("/tmp/g/pc.txt"), TEXT, "the PC's text .gz")
  eq(run("zcat /tmp/g/data.bin.gz") == BIN, true, "zcat gives the bytes back")
  eq(run("cat /tmp/g/notes.txt | gzip -1 | gunzip"), TEXT, "through a pipe")
  run("gzip -c /tmp/g/notes.txt > /tmp/g/copy.gz")
  ok(file("/tmp/g/notes.txt"), "-c leaves the file")
  eq(host("gzip -dc " .. q(ROOT .. "/tmp/g/copy.gz")), TEXT)
  local out = run("gzip -v -k /tmp/src/a.txt")
  has(out, "a.txt:"); has(out, "replaced with a.txt.gz")
  has(run("gzip /tmp/src/a.txt"), "already exists (-f overwrites it)")
  has(run("gzip /tmp/g/data.bin.gz"), "already has the .gz suffix")
  has(run("gunzip /tmp/src/a.txt"), "unknown suffix")
  eq(run("printf 'ab' | gzip | zcat"), "ab")
end)

test("damaged data is refused and nothing is replaced", function()
  local gz = file("/tmp/g/copy.gz")
  put("/tmp/g/bad.gz", gz:sub(1, -9) .. string.char((gz:byte(-8) + 1) % 256) .. gz:sub(-7))
  local out, rc = run("gunzip /tmp/g/bad.gz")
  eq(rc, 1); has(out, "CRC error")
  ok(file("/tmp/g/bad.gz"), "the .gz stays"); ok(not file("/tmp/g/bad"), "no half file")
  ok(not file("/tmp/g/bad.part"), "no leftovers")
  put("/tmp/g/plain.gz", "this is no gzip\n")
  has(run("gunzip /tmp/g/plain.gz"), "not in gzip format")
  put("/tmp/g/short.gz", gz:sub(1, 30))
  has(run("gunzip /tmp/g/short.gz"), "unexpected end")
end)

test("tar -z, and .tar.gz from the PC", function()
  local _, rc = run("tar -czf /tmp/x.tgz -C /tmp src")
  eq(rc, 0)
  ok(file("/tmp/x.tgz"):sub(1, 2) == "\31\139", "it is gzip")
  eq(host("tar -tzf " .. q(ROOT .. "/tmp/x.tgz") .. " | sort"), "src/\nsrc/a.txt\nsrc/a.txt.gz\nsrc/sub/\nsrc/sub/b.bin\n")
  os.execute("mkdir -p " .. q(ROOT .. "/tmp/pcout") .. " && tar -xzf " .. q(ROOT .. "/tmp/x.tgz") .. " -C " .. q(ROOT .. "/tmp/pcout"))
  eq(file("/tmp/pcout/src/sub/b.bin"), BIN, "the PC unpacks ByteOS's .tar.gz")
  os.execute("tar -czf " .. q(ROOT .. "/tmp/pc.tar.gz") .. " -C " .. q(ROOT .. "/tmp") .. " src")
  run("mkdir /tmp/z1 /tmp/z2")
  eq(select(2, run("tar -xzf /tmp/pc.tar.gz -C /tmp/z1")), 0)
  eq(file("/tmp/z1/src/sub/b.bin"), BIN)
  eq(select(2, run("tar -xf /tmp/pc.tar.gz -C /tmp/z2")), 0, "recognized without -z")
  eq(file("/tmp/z2/src/a.txt"), "hello\n")
  has(run("tar -tf /tmp/pc.tar.gz"), "src/sub/b.bin")
  eq(run("tar -tf - src/a.txt < /tmp/x.tgz"), "src/a.txt\n", "from the input, one member")
  eq(run("tar -czf - -C /tmp src | tar -tzf - src/a.txt"), "src/a.txt\n", "through a pipe")
  local out = run("tar -xzf /tmp/src/a.txt -C /tmp/z1")
  has(out, "not in gzip format")
  has(run("tar -cjf /tmp/x.tbz -C /tmp src"), "only gzip compression (-z)")
end)

test("xxd: the vim layout, -p, -c, -g, -s, -l and back with -r", function()
  put("/tmp/h.txt", "Hello, ByteOS!\n")
  eq(run("xxd /tmp/h.txt"), "00000000: 4865 6c6c 6f2c 2042 7974 654f 5321 0a    Hello, ByteOS!.\n")
  eq(run("xxd -p /tmp/h.txt"), "48656c6c6f2c20427974654f53210a\n")
  eq(run("xxd -c 8 -g 4 /tmp/h.txt"), "00000000: 48656c6c 6f2c2042  Hello, B\n00000008: 7974654f 53210a    yteOS!.\n")
  eq(run("xxd -s 7 -l 6 /tmp/h.txt"), "00000007: 4279 7465 4f53                           ByteOS\n")
  eq(run("printf 'AB' | xxd -g 0"), "00000000: 4142                              AB\n")
  put("/tmp/bin.dat", noise(300, 7))
  run("xxd /tmp/bin.dat > /tmp/bin.hex")
  run("xxd -r /tmp/bin.hex > /tmp/bin.back")
  eq(file("/tmp/bin.back"), file("/tmp/bin.dat"), "-r undoes a dump")
  run("xxd -p /tmp/bin.dat | xxd -r -p > /tmp/bin.back2")
  eq(file("/tmp/bin.back2"), file("/tmp/bin.dat"), "-r -p undoes a plain dump")
  has(run("xxd -c x /tmp/h.txt"), "-c needs a number")
end)
