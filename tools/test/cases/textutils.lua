put("/tmp/abc.txt", "one\ntwo\n\nthree\n")

test("rmdir removes only empty directories, -p the parents too", function()
  run("mkdir /tmp/e; mkdir /tmp/full; touch /tmp/full/x")
  local _, rc = run("rmdir /tmp/e")
  eq(rc, 0); ok(not kernel.fs.exists("/tmp/e"), "empty directory removed")
  local out, bad = run("rmdir /tmp/full")
  eq(bad, 1); has(out, "Directory not empty"); ok(kernel.fs.exists("/tmp/full/x"), "the full one stays")
  has(run("rmdir /tmp/abc.txt"), "not a directory")
  run("mkdir /tmp/p; mkdir /tmp/p/q; mkdir /tmp/p/q/r")
  _G.PWD = "/tmp"
  eq(select(2, run("rmdir -p p/q/r")), 0)
  _G.PWD = "/"
  ok(not kernel.fs.exists("/tmp/p"), "-p removed the parents")
end)

test("stat", function()
  local out = run("stat /tmp/abc.txt")
  has(out, "File: /tmp/abc.txt"); has(out, "Size: 15"); has(out, "regular file")
  has(out, "Access: (0666/-rw-rw-rw-)  Uid: root  Gid: root")
  has(run("stat /etc"), "directory")
  put("/tmp/secret", "x")
  run("chmod 600 /tmp/secret")
  eq(run("stat -c '%a %U %G %F' /tmp/secret"), "600 root root regular file\n")
  eq(run("stat -c '%n:%s' /tmp/abc.txt /tmp/secret"), "/tmp/abc.txt:15\n/tmp/secret:1\n")
  run("chmod 640 /tmp/abc.txt")
  eq(run("stat -c %A /tmp/abc.txt"), "-rw-r-----\n")
  local missing, rc = run("stat /nope")
  eq(rc, 1); has(missing, "cannot stat '/nope'")
end)

test("printf", function()
  eq(run("printf 'hi\\n'"), "hi\n")
  eq(run("printf '%s=%d\\n' a 1 b 2"), "a=1\nb=2\n", "the format is used again")
  eq(run("printf '[%5s|%-4s|%05d|%.2f]' ab cd 42 3.14159"), "[   ab|cd  |00042|3.14]")
  eq(run("printf '%x %X %o %c %%\\n' 255 255 8 hello"), "ff FF 10 h %\n")
  eq(run("printf '%s\\t%s\\n' a"), "a\t\n", "missing arguments are empty")
  eq(run("printf 'a\\\\b'"), "a\\b")
  eq(run("printf '\\0101\\e'"), "A\27")
  eq(run("printf '%s' 'x\\ny'"), "x\\ny", "arguments are not unescaped")
  local out, rc = run("printf '%d' abc")
  eq(rc, 1); has(out, "expected a number")
end)

test("yes stops after 1000 lines into a pipe", function()
  eq(run("yes | head -n 2"), "y\ny\n")
  eq(run("yes no way | wc -l"):match("%d+"), "1000")
  eq(run("yes ok | tail -n 1"), "ok\n")
end)

test("tac, rev", function()
  eq(run("tac /tmp/abc.txt"), "three\n\ntwo\none\n")
  eq(run("seq 3 | tac"), "3\n2\n1\n")
  eq(run("echo hello | rev"), "olleh\n")
  eq(run("printf 'aä\\nxyz' | rev"), "äa\nzyx\n", "characters, not bytes")
end)

test("nl", function()
  eq(run("nl /tmp/abc.txt"), "     1\tone\n     2\ttwo\n       \n     3\tthree\n")
  eq(run("nl -b a -w 2 -s ': ' /tmp/abc.txt"), " 1: one\n 2: two\n 3: \n 4: three\n")
end)

test("paste", function()
  put("/tmp/p1", "a\nb\nc\n"); put("/tmp/p2", "1\n2\n")
  eq(run("paste /tmp/p1 /tmp/p2"), "a\t1\nb\t2\nc\t\n")
  eq(run("paste -d , /tmp/p1 /tmp/p2"), "a,1\nb,2\nc,\n")
  eq(run("paste -s /tmp/p1"), "a\tb\tc\n")
  eq(run("seq 4 | paste -s -d +"), "1+2+3+4\n")
end)

test("cmp", function()
  put("/tmp/c1", "abc\ndef\n"); put("/tmp/c2", "abc\ndxf\n"); put("/tmp/c3", "abc\n")
  local out, rc = run("cmp /tmp/c1 /tmp/c2")
  eq(rc, 1); eq(out, "/tmp/c1 /tmp/c2 differ: byte 6, line 2\n")
  eq(select(2, run("cmp /tmp/c1 /tmp/c1")), 0)
  local s, rs = run("cmp -s /tmp/c1 /tmp/c2")
  eq(s, ""); eq(rs, 1)
  has(run("cmp /tmp/c1 /tmp/c3"), "EOF on /tmp/c3 after byte 4")
  eq(select(2, run("cmp /tmp/c1 /nope")), 2)
end)

test("base64 encodes and decodes", function()
  eq(run("printf 'Man' | base64"), "TWFu\n")
  eq(run("printf 'Ma' | base64"), "TWE=\n")
  eq(run("printf 'M' | base64"), "TQ==\n")
  eq(run("printf 'TWFu\\nTQ==' | base64 -d"), "ManM")
  local bin = {}
  for b = 0, 255 do bin[#bin + 1] = string.char(b) end
  put("/tmp/bin", table.concat(bin))
  run("base64 /tmp/bin > /tmp/bin.txt")
  local enc = file("/tmp/bin.txt")
  eq(#enc:match("^[^\n]*"), 76, "wrapped at 76")
  run("base64 -d /tmp/bin.txt > /tmp/bin.out")
  eq(file("/tmp/bin.out"), table.concat(bin), "every byte survives the round trip")
  lacks(run("base64 -w 0 /tmp/bin"):sub(1, -2), "\n", "-w 0 does not wrap")
  has(run("echo 'a*b' | base64 -d"), "invalid input")
end)
