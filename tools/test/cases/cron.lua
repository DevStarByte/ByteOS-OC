-- Scheduled jobs: crontab lines, the crontab command and crond.
users()
local cron = require("cron")
local function idle(sec) kernel.event.pull(sec) end
local function at(min, hour, day, month, wday) return { min = min, hour = hour, day = day, month = month, wday = wday } end

test("crontab lines: fields, ranges, steps, lists, names, macros", function()
  local j = cron.parse("*/15 * * * * echo hi")
  eq(j.cmd, "echo hi")
  ok(cron.due(j, at(0, 3, 1, 1, 4)) and cron.due(j, at(45, 3, 1, 1, 4)), "*/15 at :00 and :45")
  ok(not cron.due(j, at(10, 3, 1, 1, 4)), "not at :10")
  j = cron.parse("0 7 * * mon-fri  sh ~/bin/morning.sh")
  ok(cron.due(j, at(0, 7, 5, 10, 1)), "monday 7:00")
  ok(not cron.due(j, at(0, 7, 4, 10, 0)), "not sunday")
  j = cron.parse("30 12 1,15 * 7 x")
  ok(cron.due(j, at(30, 12, 15, 2, 3)), "day 15 matches although it is not sunday")
  ok(cron.due(j, at(30, 12, 9, 2, 0)), "sunday (7) matches although it is the 9th")
  ok(not cron.due(j, at(30, 12, 9, 2, 3)))
  j = cron.parse("0 0 * jan,jul * x")
  ok(cron.due(j, at(0, 0, 1, 7, 2)) and not cron.due(j, at(0, 0, 1, 8, 2)), "month names")
  j = cron.parse("5/20 * * * * x")
  ok(cron.due(j, at(25, 1, 1, 1, 1)) and not cron.due(j, at(20, 1, 1, 1, 1)), "N/step starts at N")
  j = cron.parse("@daily rm -r /tmp/cache")
  eq(j.cmd, "rm -r /tmp/cache")
  ok(cron.due(j, at(0, 0, 3, 3, 3)) and not cron.due(j, at(0, 1, 3, 3, 3)))
  ok(cron.parse("@reboot echo up").reboot)
  eq(cron.parse("# a comment"), nil); eq(cron.parse("   "), nil)
  local u = cron.parse("0 * * * * alice echo from-etc", true)
  eq(u.user, "alice"); eq(u.cmd, "echo from-etc")
end)

test("mistakes are reported", function()
  local _, why = cron.parse("61 * * * * x"); has(why, "minute '61' is out of range")
  _, why = cron.parse("* * * *"); has(why, "too few fields")
  _, why = cron.parse("* * * * *"); has(why, "no command")
  _, why = cron.parse("5-1 * * * * x"); has(why, "backwards range")
  _, why = cron.parse("@sometimes x"); has(why, "unknown @sometimes")
  _, why = cron.parse("* * * * blursday x"); has(why, "weekday 'blursday' is out of range")
end)

test("crontab installs, lists and removes your jobs", function()
  as("alice", function()
    put("/tmp/jobs", "# mine\n*/5 * * * * echo tick\n")
    local _, rc = run("crontab /tmp/jobs")
    eq(rc, 0)
    eq(run("crontab -l"), "# mine\n*/5 * * * * echo tick\n")
    eq(file("/home/alice/.crontab"), "# mine\n*/5 * * * * echo tick\n")
    local out, bad = run("echo '99 * * * * x' | crontab -")
    eq(bad, 1); has(out, "line 1: minute '99' is out of range"); has(out, "not installed")
    eq(file("/home/alice/.crontab"), "# mine\n*/5 * * * * echo tick\n", "a bad crontab replaces nothing")
    has(run("crontab -u bob -l"), "only root may change another user's crontab")
    run("crontab -r")
    ok(not file("/home/alice/.crontab"), "removed")
    local o, r = run("crontab -l")
    has(o, "no crontab for alice"); eq(r, 1)
  end)
  put("/home/bob/.crontab", "@hourly echo bob\n")
  eq(run("crontab -u bob -l"), "@hourly echo bob\n", "root may look at anyone's")
end)

test("jobs run as their user, and what they print goes to the log", function()
  put("/home/alice/.crontab", "* * * * * whoami > /tmp/cron-who; echo said-by-cron\nbad line here\n")
  put("/etc/crontab", "* * * * * bob echo etc-job > /tmp/cron-etc\n")
  local jobs = cron.tabs()
  eq(#jobs, 3, "bob's @hourly, alice's job, /etc/crontab's job")
  for _, j in ipairs(jobs) do
    if cron.due(j, at(1, 2, 3, 4, 5)) then cron.run(j) end
  end
  idle(0.5)
  eq(file("/tmp/cron-who"), "alice\n")
  eq(file("/tmp/cron-etc"), "etc-job\n")
  local log = file("/var/log/messages")
  has(log, "crond: (alice) CMD (whoami > /tmp/cron-who; echo said-by-cron)")
  has(log, "crond: said-by-cron")
  has(log, "/home/alice/.crontab:2: too few fields")
end)

test("crond is a service that runs @reboot jobs and due jobs", function()
  put("/home/alice/.crontab", "@reboot echo booted > /tmp/cron-boot\n* * * * * echo minute >> /tmp/cron-min\n")
  os.remove(ROOT .. "/etc/crontab")
  ok(file("/etc/systemd/system/crond.service"), "the unit is shipped")
  local out, rc = run("systemctl start crond")
  eq(rc, 0, out)
  idle(1)
  eq(file("/tmp/cron-boot"), "booted\n")
  has(file("/tmp/cron-min") or "", "minute\n", "the job of the current minute ran")
  has(run("systemctl status crond"), "active")
  run("systemctl stop crond")
end)

test("crontab offers root to start crond", function()
  run("systemctl stop crond")
  put("/tmp/rootjobs", "@hourly echo hi\n")
  answers({ "y" })
  local out = run("crontab /tmp/rootjobs")
  has(out, "Start it now and at every boot?"); has(out, "crond started")
  has(run("systemctl status crond"), "active")
  has(file("/etc/systemd/enabled"), "crond")
  run("systemctl stop crond")
  answers({ "n" })
  lacks(run("crontab /tmp/rootjobs"), "crond started", "no is no")
  as("alice", function()
    has(run("crontab /tmp/rootjobs"), "sudo systemctl enable --now crond", "others are told how")
  end)
end)
