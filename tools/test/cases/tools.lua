-- lua, timeout, time, uptime and watch (tar is a package: see packages.lua).
local function sh(c) return os.execute(c) == true end
local function q(p) return "'" .. p:gsub("'", "'\\''") .. "'" end
local hostTar = sh("command -v tar >/dev/null 2>&1")

test("lua -e, a file with arguments, code from a pipe", function()
  eq(run("lua -e 'print(1 + 1)'"), "2\n")
  eq(run("lua -e 'X = 5' -e 'print(X * 2)'"), "10\n", "-e chunks share their variables")
  put("/tmp/s.lua", "#!/bin/lua\nprint(arg[0], arg[1], ...)\nreturn 3\n")
  local out, rc = run("lua /tmp/s.lua a b")
  eq(out, "/tmp/s.lua\ta\ta\tb\n"); eq(rc, 3, "a returned number is the exit status")
  eq(run("echo 'print(40 + 2)' | lua -"), "42\n")
  local err, bad = run("lua -e 'x ='")
  has(err, "lua: "); eq(bad, 1)
  local _, missing = run("lua /tmp/nope.lua")
  eq(missing, 1)
  has(run("lua -e 'print(k.user(), fs.exists(\"/etc\"), type(component))'"), "root\ttrue\ttable")
end)

test("the lua prompt: values, multi-line chunks, errors, exit", function()
  keys({ "1 + 2", "<enter>", "function f(x)", "<enter>", "return x * 2", "<enter>", "end", "<enter>",
    "f(21)", "<enter>", "t = { 1, 'a', b = true }", "<enter>", "=t", "<enter>", "nosuch()", "<enter>",
    "'text'", "<enter>", "half typed", "<ctrl+c>", "exit", "<enter>" })
  local out, rc = run("lua")
  eq(rc, 0)
  has(out, "3\n"); has(out, ">> "); has(out, "42\n")
  has(out, '{ 1, "a", b = true }'); has(out, "attempt to call a nil value"); has(out, "text\n")
  keys({ "<ctrl+d>" })
  local _, rc2 = run("lua")
  eq(rc2, 0, "Ctrl+D leaves")
end)

test("timeout stops a slow command and passes on a quick one's status", function()
  local start = os.clock()
  local _, rc = run("timeout 0.2 sleep 10")
  eq(rc, 124)
  ok(os.clock() - start < 5, "stopped early")
  local out, rc2 = run("timeout 5 echo 'hi there'")
  eq(out, "hi there\n"); eq(rc2, 0)
  local _, rc3 = run("timeout 5 false")
  eq(rc3, 1)
  local _, rc4 = run("timeout 1x sleep 1")
  eq(rc4, 125)
end)

test("time", function()
  local out, rc = run("time echo hi")
  ok(out:match("^hi\nreal %d+%.%d%ds\n$"), "output: " .. out)
  eq(rc, 0)
  local _, rc2 = run("time false")
  eq(rc2, 1)
end)

test("uptime", function()
  local out = run("uptime")
  ok(out:match("^%d%d:%d%d:%d%d up %d+ min,  1 user,  %d+ process"), "uptime: " .. out)
  ok(run("uptime -p"):match("^up %d+ minutes?\n$"), "uptime -p")
  ok(run("uptime -s"):match("^%d%d%d%d%-%d%d%-%d%d %d%d:%d%d:%d%d\n$"), "uptime -s")
end)

test("watch shows the command and quits on q", function()
  signals({ { "key_down", "keyboard", 113, 16 } })
  local out, rc = run("watch -n 0.1 echo hi")
  has(out, "Every 0.1s: echo hi"); has(out, "hi\n"); eq(rc, 0)
  signals({ { "key_down", "keyboard", 113, 16 } })
  local plain = run("watch -t -n 0.1 'echo a; echo b'")
  lacks(plain, "Every"); has(plain, "a\nb\n")
end)

test("the lua prompt remembers what was typed, also next time", function()
  keys({ "41 + 1", "<enter>", "exit", "<enter>" })
  run("lua")
  ok(file("/home/root/.lua_history"):sub(-7) == "41 + 1\n", "the line was added to ~/.lua_history")
  keys({ "<up>", "<enter>", "exit", "<enter>" })
  has(run("lua"), "42\n", "↑ brings back the line from the last run")
end)
